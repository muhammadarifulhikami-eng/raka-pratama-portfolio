document.addEventListener('DOMContentLoaded', () => {
  const htmlEl = document.documentElement;
  const themeBtn = document.getElementById('themeToggle');
  const langBtns = document.querySelectorAll('#langSwitch .lang-btn');
  const navLinks = document.querySelectorAll('.nav-links .nav-link[href]');
  const mobileBtn = document.getElementById('mobileMenuBtn');
  const mobileDrawer = document.getElementById('mobileDrawer');

  let currentLang = 'id';
  let showingAllWorks = false;
  let currentSlide = 0;

  // Theme Toggle
  themeBtn.addEventListener('click', () => {
    const next = htmlEl.getAttribute('data-theme') === 'light' ? 'dark' : 'light';
    htmlEl.setAttribute('data-theme', next);
  });

  // Bilingual Switch
  function applyLanguage(lang) {
    currentLang = lang;
    htmlEl.lang = lang;
    const dict = I18N[lang];
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const k = el.getAttribute('data-i18n');
      if (dict[k]) el.textContent = dict[k];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      const k = el.getAttribute('data-i18n-ph');
      if (dict[k]) el.setAttribute('placeholder', dict[k]);
    });
    const toggleBtn = document.getElementById('toggleAllWorksBtn');
    toggleBtn.textContent = showingAllWorks ? dict['work.viewLess'] : dict['work.viewAll'];
    renderTestimonial(currentSlide);
  }

  langBtns.forEach((btn) => {
    btn.addEventListener('click', () => {
      langBtns.forEach((b) => b.classList.remove('active'));
      btn.classList.add('active');
      applyLanguage(btn.dataset.lang);
    });
  });

  // Mobile Menu
  mobileBtn.addEventListener('click', () => {
    const open = mobileDrawer.classList.toggle('open');
    mobileBtn.setAttribute('aria-expanded', String(open));
  });

  mobileDrawer.querySelectorAll('a, button').forEach((item) => {
    item.addEventListener('click', () => {
      mobileDrawer.classList.remove('open');
      mobileBtn.setAttribute('aria-expanded', 'false');
    });
  });

  // Toggle 4 vs 6 Projects
  const toggleAllBtn = document.getElementById('toggleAllWorksBtn');
  toggleAllBtn.addEventListener('click', () => {
    showingAllWorks = !showingAllWorks;
    document.querySelectorAll('.work-extra').forEach((card) => {
      card.classList.toggle('is-hidden', !showingAllWorks);
    });
    toggleAllBtn.textContent = showingAllWorks ? I18N[currentLang]['work.viewLess'] : I18N[currentLang]['work.viewAll'];
  });

  // Process Interactive Nodes
  const procCards = document.querySelectorAll('.proc-card');
  const rmNodes = document.querySelectorAll('.rm-node');
  procCards.forEach((card) => {
    const activate = () => {
      const step = card.dataset.step;
      procCards.forEach((c) => c.classList.toggle('active', c.dataset.step === step));
      rmNodes.forEach((n) => n.classList.toggle('active', n.dataset.step === step));
    };
    card.addEventListener('mouseenter', activate);
    card.addEventListener('click', activate);
  });

  // Testimonials Carousel
  const qEl = document.getElementById('testimonialQuote');
  const nEl = document.getElementById('testimonialName');
  const rEl = document.getElementById('testimonialRole');
  const dotEls = document.querySelectorAll('#testimonialDots .t-dot');

  function renderTestimonial(idx) {
    currentSlide = idx;
    const item = TESTIMONIALS[idx];
    qEl.textContent = currentLang === 'en' ? item.en : item.id;
    nEl.textContent = item.name;
    rEl.textContent = currentLang === 'en' ? item.roleEn : item.roleId;
    dotEls.forEach((d, i) => d.classList.toggle('active', i === idx));
  }

  dotEls.forEach((d) => {
    d.addEventListener('click', () => renderTestimonial(Number(d.dataset.slide)));
  });

  setInterval(() => {
    renderTestimonial((currentSlide + 1) % TESTIMONIALS.length);
  }, 6000);

  // Modal Engine (Case Study / About Me / Insights)
  const modal = document.getElementById('uiModal');
  const modalTag = document.getElementById('uiModalTag');
  const modalTitle = document.getElementById('uiModalTitle');
  const modalSub = document.getElementById('uiModalSub');
  const modalBody = document.getElementById('uiModalBody');

  function openModal(tag, title, sub, htmlContent) {
    modalTag.textContent = tag;
    modalTitle.textContent = title;
    modalSub.textContent = sub;
    modalBody.innerHTML = htmlContent;
    modal.classList.add('open');
  }

  function closeModal() {
    modal.classList.remove('open');
  }

  document.getElementById('uiModalClose').addEventListener('click', closeModal);
  modal.addEventListener('click', (e) => {
    if (e.target === modal) closeModal();
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeModal();
  });

  document.querySelectorAll('.work-card').forEach((card) => {
    const trigger = () => {
      const data = CASE_STUDIES[card.dataset.case];
      if (!data) return;
      const kpisHtml = data.kpis
        .map((k) => `<div class="modal-kpi-box"><strong>${k.v}</strong><span>${k.l}</span></div>`)
        .join('');
      const tagsHtml = data.tags.map((t) => `<span>${t}</span>`).join('');
      openModal(
        data.tag,
        data.title,
        data.sub,
        `<div class="modal-kpi-strip">${kpisHtml}</div><p>${data.desc}</p><div class="modal-tags">${tagsHtml}</div>`
      );
    };
    card.addEventListener('click', trigger);
    card.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        trigger();
      }
    });
  });

  document.getElementById('aboutMeBtn').addEventListener('click', () => {
    openModal(
      'TENTANG RAKA PRATAMA',
      'UI/UX & Web Designer · Jakarta',
      '5+ tahun merancang produk SaaS, Fintech, dan website brand Indonesia.',
      `<p>Lulusan Desain Produk & Komunikasi Visual di Jakarta yang berfokus menjembatani riset pengguna dengan eksekusi visual yang tenang, rapi, dan siap dikembangkan tim engineering.</p>
       <div class="modal-kpi-strip">
         <div class="modal-kpi-box"><strong>47+</strong><span>Proyek Rilis</span></div>
         <div class="modal-kpi-box"><strong>31</strong><span>Klien Aktif & Alumni</span></div>
         <div class="modal-kpi-box"><strong>98%</strong><span>Tingkat Kepuasan</span></div>
       </div>
       <div class="modal-tags">
         <span>Figma & Tokens</span><span>Design Systems</span><span>Framer</span><span>React / HTML / CSS</span>
       </div>`
    );
  });

  const openInsights = () => {
    openModal(
      'WAWASAN & ARTIKEL',
      'Catatan Desain Produk Digital',
      'Tulisan singkat mengenai Design Systems, UX Finansial, dan Web Craftsmanship.',
      `<div class="modal-kpi-box"><strong>01 · Design Token untuk Startup Berkembang</strong><span>Menjaga konsistensi komponen di Web &amp; Mobile sejak hari pertama.</span></div>
       <div class="modal-kpi-box"><strong>02 · Psikologi Kepercayaan di Landing Page</strong><span>Bagaimana ruang kosong dan tipografi meningkatkan konversi B2B.</span></div>
       <div class="modal-kpi-box"><strong>03 · Kolaborasi Desainer × Engineer</strong><span>Checklist handoff bersih untuk mengurangi revisi pengembangan UI.</span></div>`
    );
  };

  document.getElementById('insightsBtn').addEventListener('click', openInsights);
  document.getElementById('mobileInsightsBtn').addEventListener('click', openInsights);
  document.querySelectorAll('.footer-insights-trigger').forEach((el) => {
    el.addEventListener('click', (e) => {
      e.preventDefault();
      openInsights();
    });
  });

  // Forms
  const contactForm = document.getElementById('contactForm');
  const contactFeedback = document.getElementById('contactFeedback');
  contactForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const name = document.getElementById('cfName').value.trim();
    const email = document.getElementById('cfEmail').value.trim();
    const msg = document.getElementById('cfMessage').value.trim();
    if (!name || !email.includes('@') || !msg) {
      contactFeedback.className = 'form-feedback error';
      contactFeedback.textContent = currentLang === 'en'
        ? 'Please complete your name, valid email, and project message.'
        : 'Mohon lengkapi nama, email valid, dan detail singkat proyek Anda.';
      return;
    }
    contactFeedback.className = 'form-feedback';
    contactFeedback.textContent = currentLang === 'en'
      ? `Thank you, ${name}! Your brief has been recorded. Raka will reply via ${email} within 1×24h.`
      : `Terima kasih, ${name}! Pesan Anda sudah diterima. Raka akan membalas ke ${email} dalam 1×24 jam.`;
    contactForm.reset();
  });

  const newsForm = document.getElementById('newsletterForm');
  const newsFeedback = document.getElementById('newsFeedback');
  newsForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const email = document.getElementById('newsEmail').value.trim();
    if (!email.includes('@')) {
      newsFeedback.style.color = '#f87171';
      newsFeedback.textContent = currentLang === 'en' ? 'Enter a valid email address.' : 'Masukkan alamat email yang valid.';
      return;
    }
    newsFeedback.style.color = '#4ade80';
    newsFeedback.textContent = currentLang === 'en'
      ? 'Subscribed! Monthly design notes will arrive soon.'
      : 'Berhasil berlangganan! Catatan desain akan dikirim ke email Anda.';
    newsForm.reset();
  });

  // Scroll-Spy Active Nav
  const sectionIds = ['home', 'work', 'services', 'about', 'process', 'contact'];
  const updateActiveNav = () => {
    const pos = window.scrollY + 140;
    let activeId = 'home';
    sectionIds.forEach((id) => {
      const sec = document.getElementById(id);
      if (sec && sec.offsetTop <= pos) activeId = id;
    });
    navLinks.forEach((link) => {
      link.classList.toggle('active', link.getAttribute('href') === `#${activeId}`);
    });
  };
  window.addEventListener('scroll', updateActiveNav, { passive: true });
  updateActiveNav();
});
